package ru.ryadom.safety

object RiskEngine {
    private data class Rule(val category: String, val weight: Int, val words: List<String>)
    private val rules = listOf(
        Rule("Нецензурная лексика", 2, listOf("блять","бля","сука","нахуй","пиздец")),
        Rule("Оскорбление", 10, listOf("ты тупой","ты тупая","дебил","идиот","урод")),
        Rule("Травля", 22, listOf("тебя никто не любит","все над тобой смеются","мы тебя ненавидим")),
        Rule("Угроза", 45, listOf("я тебя убью","тебе конец","изобью тебя","тебя отпиздят","зарежу тебя")),
        Rule("Секретность", 25, listOf("никому не говори","не говори родителям","удали переписку","наш секрет")),
        Rule("Груминг", 25, listOf("сколько тебе лет","ты один дома","ты одна дома","родители дома")),
        Rule("Сексуальный запрос", 60, listOf("скинь голое фото","пришли нюдс","покажи грудь","разденься на камеру")),
        Rule("Опасная встреча", 45, listOf("приходи один","приходи одна","встретимся без родителей")),
        Rule("Наркотики", 50, listOf("мефедрон","закладка","кладмен","купить траву","амфетамин")),
        Rule("Самоповреждение", 80, listOf("хочу умереть","не хочу жить","покончу с собой","убью себя","вскрою вены")),
        Rule("Оружие", 60, listOf("принесу нож","принесу пистолет","оружие в школу")),
        Rule("Шантаж", 65, listOf("выложу твои фото","разошлю твои фото","если не сделаешь я всем покажу")),
        Rule("Вымогательство", 60, listOf("переведи деньги иначе","скинь деньги иначе","гони деньги"))
    )

    fun analyze(text: String): Pair<Int,List<String>> {
        val s = text.lowercase().replace(Regex("\\s+"), " ")
        var score = 0
        val cats = mutableListOf<String>()
        for (r in rules) if (r.words.any { s.contains(it) }) {
            score += r.weight
            cats += r.category
        }
        if ((s.contains("никому не говори") || s.contains("не говори родителям")) &&
            (s.contains("скинь фото") || s.contains("пришли фото"))) {
            score += 45
            cats += "Подозрительная просьба о фото"
        }
        return minOf(100, score) to cats.distinct()
    }
}
