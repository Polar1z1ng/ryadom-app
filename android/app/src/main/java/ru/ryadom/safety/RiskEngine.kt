    fun analyze(text: String): Pair<Int, List<String>> {
        val s = normalize(text)
        if (s.isBlank()) return 0 to emptyList()

        var score = 0
        var matchedRuleCount = 0
        val categories = linkedSetOf<String>()

        for (rule in rules) {
            if (rule.phrases.any { s.contains(normalize(it)) }) {
                score = maxOf(score, rule.severity)
                matchedRuleCount++
                categories += rule.category
            }
        }

        // --- Сценарные комбинации: несколько слабых признаков дают критический уровень ---

        val secrecy = containsAny(s, listOf(
            "никому не говори", "не говори родителям", "наш секрет",
            "только между нами", "удали переписку", "не показывай переписку"
        ))

        val photoRequest = containsAny(s, listOf(
            "скинь фото", "пришли фото", "скинь видео", "пришли видео",
            "покажи себя", "покажи тело", "разденься"
        ))

        val sexual = containsAny(s, listOf(
            "голое фото", "нюдс", "нюдсы", "без одежды", "интимное фото",
            "разденься", "покажи грудь", "покажи попу"
        ))

        val meeting = containsAny(s, listOf(
            "встретимся", "приходи", "я заеду за тобой", "выйди ко мне",
            "приходи ко мне домой"
        ))

        val childProbe = containsAny(s, listOf(
            "сколько тебе лет", "ты один дома", "ты одна дома",
            "родители дома", "когда родители уйдут", "где ты живешь",
            "где ты живешь", "в какой школе учишься"
        ))

        val blackmail = containsAny(s, listOf(
            "выложу", "разошлю", "всем покажу", "заплати",
            "иначе покажу", "иначе выложу", "иначе разошлю"
        ))

        if (secrecy && sexual) {
            score = 100
            categories += "Груминг: секретность + сексуальный запрос"
        } else if (secrecy && photoRequest) {
            score = maxOf(score, 95)
            categories += "Груминг: секретность + запрос фото/видео"
        }

        if (childProbe && photoRequest) {
            score = maxOf(score, 95)
            categories += "Груминг: выяснение уязвимости + запрос контента"
        }

        if (secrecy && meeting) {
            score = maxOf(score, 95)
            categories += "Опасная тайная встреча"
        }

        if (blackmail && (sexual || photoRequest)) {
            score = 100
            categories += "Сексуальный шантаж / вымогательство"
        }

        // --- Контекст адресного оскорбления ---
        // Мат сам по себе может быть частью обычной речи, но мат + обращение к человеку
        // или серия уничижительных формулировок уже должна попадать родителю.
        val directedAtPerson = containsAny(s, listOf(
            "ты ", "тебя ", "тебе ", "твоя ", "твой ", "твое ", "твоё "
        ))

        val harshInsult = containsAny(s, listOf(
            "мразь", "тварь", "ублюдок", "ублюдок", "чмо", "гнида", "падла",
            "шлюха", "долбоеб", "долбоебка", "ебанутый", "ебанутая",
            "тупорылый", "тупорылая", "уебок", "уебок", "уродина"
        ))

        val humiliatingPhrase = containsAny(s, listOf(
            "заткнись", "закрой рот", "никому не нужен", "никому не нужна",
            "всем противно", "все тебя ненавидят", "над тобой все смеются",
            "с тобой никто не дружит"
        ))

        val profanity = containsAny(s, listOf(
            "сука", "блять", "блядь", "нахуй", "заебал", "заебала",
            "ебаный", "ебаная", "хуй", "пиздец"
        ))

        if (directedAtPerson && harshInsult) {
            score = maxOf(score, 65)
            categories += "Грубое адресное оскорбление"
        }

        if (directedAtPerson && profanity && humiliatingPhrase) {
            score = maxOf(score, 70)
            categories += "Агрессивное унижение"
        }

        if (harshInsult && humiliatingPhrase) {
            score = maxOf(score, 75)
            categories += "Травля / унижение"
        }

        val authority = containsAny(s, listOf(
            "сотрудник банка", "служба безопасности банка", "сотрудник фсб",
            "сотрудник полиции", "следователь", "центробанк", "прокуратура"
        ))

        val codeRequest = containsAny(s, listOf(
            "код из смс", "код из sms", "код подтверждения",
            "продиктуйте код", "назовите код", "сообщите код", "пришлите код"
        ))

        val moneyAction = containsAny(s, listOf(
            "переведи деньги", "переведите деньги", "переведи средства",
            "переведите средства", "сними деньги", "снимите деньги",
            "выведи деньги", "выведите деньги"
        ))

        val remoteAccess = containsAny(s, listOf(
            "anydesk", "rustdesk", "teamviewer", "удаленный доступ", "удалённый доступ"
        ))

        if (authority && codeRequest) {
            score = 100
            categories += "Мошенничество: представитель организации + запрос кода"
        }

        if (authority && moneyAction) {
            score = 100
            categories += "Мошенничество: представитель организации + перевод денег"
        }

        if (authority && remoteAccess) {
            score = 100
            categories += "Мошенничество: представитель организации + удалённый доступ"
        }

        // Несколько независимых умеренных признаков усиливают приоритет,
        // но не заменяют критические правила выше.
        if (matchedRuleCount >= 2 && score in 1..89) {
            score = minOf(95, score + minOf(20, (matchedRuleCount - 1) * 10))
        }

        return score.coerceIn(0, 100) to categories.toList()
    }

    private fun containsAny(text: String, phrases: List<String>): Boolean =
        phrases.any { text.contains(normalize(it)) }

    private fun normalize(value: String): String =
        value.lowercase(Locale.ROOT)
            .replace('ё', 'е')
            .replace(Regex("[\\n\\r\\t]+"), " ")
            .replace(Regex("[^a-zа-я0-9@+% ]"), " ")
            .replace(Regex("\\s+"), " ")
            .trim()
}
